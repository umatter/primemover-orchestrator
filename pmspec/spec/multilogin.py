"""The Multilogin X profile pmspec sends, and the vocabulary its flags accept.

Both halves live here rather than in `converter.py` because the validator needs
them too, and importing the converter for a constant made the dependency look
like a conversion step.

`MLX_FLAG_VALUES` is the table `docs/multilogin-profile-flags.md` §2 measured
against the live `POST /profile/create` (2026-09-17, 111 value probes; the
probes carried `core_version: 1`, which MLX validates *after* the flags, so
none of them created a profile). It matters at compile time because the API
rejects a bad value with a 400 -- at profile creation, i.e. at bot setup on the
VM, where it fails every bot in the experiment, exactly as the
`core_version: 142` mistake did. A wrong flag *key*, by contrast, is accepted
and silently discarded, which is why that stays a drop.
"""

from __future__ import annotations

from typing import Any

