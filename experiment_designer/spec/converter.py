class SpecConverter:
    """
    Convert parsed YAML spec to API-compatible JSON.

    Example usage:
        parser = SpecParser()
        parsed = parser.parse(yaml_content)

        converter = SpecConverter()
        result = converter.convert(parsed)

        if result.errors:
            print("Errors:", result.errors)
        else:
            api_json = result.to_json()
    """

    def __init__(self):
        self.errors: List[str] = []
        self.warnings: List[str] = []

    def convert(self, parsed: ParsedSpec) -> ConversionResult:
        """
        Convert a parsed spec to API JSON format.

        Args:
            parsed: Parsed specification

        Returns:
            ConversionResult with JSON data
        """
        self.errors = list(parsed.errors)  # Copy any parsing errors
        self.warnings = list(parsed.warnings)

        if parsed.errors:
            return ConversionResult(
                json_data=[],
                experiment_name=parsed.experiment.get("name", ""),
                experiment_description=parsed.experiment.get("description", ""),
                crawler_count=0,
                total_jobs=0,
                errors=self.errors,
                warnings=self.warnings
            )

        # Expand design if present
        # Extract seed from design for reproducibility
        design_seed = parsed.design.get("seed") if parsed.design else None
        expander = DesignExpander(seed=design_seed)
        all_crawlers = []

        for crawler_template in parsed.crawlers:
            # Check if this crawler uses the design
            if crawler_template.get("from_design") and parsed.design:
                expanded = expander.expand(
                    parsed.design,
                    crawler_template
                )
                all_crawlers.extend(expanded)
                self.errors.extend(expander.errors)
                self.warnings.extend(expander.warnings)
            else:
                all_crawlers.append(crawler_template)

        # Convert each crawler to API format
        api_crawlers = []
        total_jobs = 0

        for i, crawler in enumerate(all_crawlers):
            try:
                api_crawler = self._convert_crawler(crawler, parsed.defaults)
                api_crawlers.append(api_crawler)

                # Count jobs
                for queue in api_crawler.get("queues", []):
                    total_jobs += len(queue.get("jobs", []))

            except Exception as e:
                self.errors.append(f"Error converting crawler {i}: {e}")

        return ConversionResult(
            json_data=api_crawlers,
            experiment_name=parsed.experiment.get("name", ""),
            experiment_description=parsed.experiment.get("description", ""),
            crawler_count=len(api_crawlers),
            total_jobs=total_jobs,
            errors=self.errors,
            warnings=self.warnings
        )

    def convert_from_yaml(self, yaml_content: str) -> ConversionResult:
        """
        Convenience method to parse and convert in one step.

        Args:
            yaml_content: YAML string

        Returns:
            ConversionResult with JSON data
        """
        parser = SpecParser()
        parsed = parser.parse(yaml_content)
        return self.convert(parsed)

    def _convert_crawler(
        self,
        crawler: Dict[str, Any],
        defaults: Dict[str, Any]
    ) -> Dict[str, Any]:
        """
        Convert a crawler to API format.

        Args:
            crawler: Parsed crawler definition
            defaults: Merged defaults

        Returns:
            API-compatible crawler dict
        """
        api_crawler = {
            "name": crawler.get("name", "Crawler"),
            "description": crawler.get("description", "Generated crawler"),
            "active": 1 if crawler.get("active", True) else 0,
            "testing": 1 if crawler.get("testing", False) else 0,
        }

        # Convert configuration
        api_crawler["configuration"] = self._convert_configuration(
            crawler.get("configuration", {}),
            defaults
        )

        # Convert proxy - use crawler proxy, or fall back to defaults.proxy
        proxy_config = crawler.get("proxy")
        if proxy_config is None:
            proxy_config = defaults.get("proxy", {})
        api_crawler["proxy"] = self._convert_proxy(proxy_config, defaults)

        # Convert agent
        api_crawler["agent"] = self._convert_agent(
            crawler.get("agent", {}),
            defaults
        )

        # Convert queues
        api_crawler["queues"] = [
            self._convert_queue(q, defaults)
            for q in crawler.get("queues", [])
        ]

        return api_crawler

    def _convert_configuration(
        self,
        config: Dict[str, Any],
        defaults: Dict[str, Any]
    ) -> Dict[str, Any]:
        """Convert configuration section to API format."""
        api_config = {
            "name": config.get("name", "Configuration"),
            "description": config.get("description", "Generated configuration"),
            "active": 1,  # API expects integer for configuration.active
        }

        # Convert params
        params = config.get("params", {})
        api_config["params"] = {
            "pi": params.get("pi", 0),
            "psi": params.get("psi", 0),
            "alpha": params.get("alpha", 1),
            "tau": params.get("tau", 0),
            "kappa": params.get("kappa", 0),
            "beta": params.get("beta", 0),
            "active": True,
            "search_terms": params.get("search_terms", []),
            "media_outlet_urls": params.get("media_outlet_urls", []),
        }

        # Convert preferences
        prefs = config.get("preferences", [])
        api_config["preferences"] = self._ensure_preferences(prefs, defaults)

        return api_config

    def _ensure_preferences(
        self,
        prefs: List[Dict[str, Any]],
        defaults: Dict[str, Any]
    ) -> List[Dict[str, Any]]:
        """Ensure required preferences are present."""
        api_prefs = []
        pref_names = set()

        # Add existing preferences
        for pref in prefs:
            api_pref = {
                "name": pref.get("name", ""),
                "description": pref.get("description", pref.get("name", "")),
                "value": self._format_pref_value(pref.get("value")),
                "active": pref.get("active", True),
            }
            api_prefs.append(api_pref)
            pref_names.add(pref.get("name"))

        # Add default preferences if not present
        default_prefs = [
            ("location", defaults.get("location", "US-IL-CHICAGO")),
            ("cookie_pref", '{"accept_all": true}'),
            ("usage_type", "only_search"),
        ]

        for name, value in default_prefs:
            if name not in pref_names:
                api_prefs.append({
                    "name": name,
                    "description": name,
                    "value": value,
                    "active": True,
                })

        return api_prefs

    def _format_pref_value(self, value: Any) -> str:
        """Format a preference value as string."""
        if isinstance(value, dict):
            return json.dumps(value)
        if isinstance(value, bool):
            return str(value).lower()
        return str(value) if value is not None else ""

    def _convert_proxy(
        self,
        proxy: Dict[str, Any],
        defaults: Dict[str, Any]
    ) -> Dict[str, Any]:
        """Convert proxy section to API format."""
        # Handle 'none' - no proxy (empty hostname signals runner to skip proxy)
        if proxy == "none":
            return {
                "name": "No Proxy",
                "description": "Direct connection - no proxy",
                "hostname": "",
                "port": 0,
                "username": "",
                "password": "",
                "active": True,
                "type": "http",  # Must be valid type; empty hostname indicates no proxy
            }

        # Handle 'auto' or minimal proxy config
        if proxy == "auto" or not proxy:
            proxy = {}

        return {
            "name": proxy.get("name", "Proxy"),
            "description": proxy.get("description", "Generated proxy"),
            "hostname": proxy.get("hostname", proxy.get("host", "127.0.0.1")),
            "port": int(proxy.get("port", 8080)),
            "username": proxy.get("username", ""),
            "password": proxy.get("password", ""),
            "active": True,
            "type": proxy.get("type", defaults.get("proxy_type", "http")),
        }

    def _convert_agent(
        self,
        agent: Dict[str, Any],
        defaults: Dict[str, Any]
    ) -> Dict[str, Any]:
        """Convert agent section to API format."""
        api_agent = {
            "name": agent.get("name", "Agent"),
            "description": agent.get("description", "Generated agent"),
            "identification": agent.get("identification", defaults.get("browser", "mlx")),
            "multilogin_id": agent.get("multilogin_id"),
            "location": agent.get("location", defaults.get("location", "US-IL-CHICAGO")),
            "active": 1,
        }

        # Handle multilogin_profile
        profile = agent.get("multilogin_profile")
        if profile:
            if isinstance(profile, dict):
                # Merge with defaults
                merged = copy.deepcopy(DEFAULT_MULTILOGIN_PROFILE)
                self._deep_merge(merged, profile)
                api_agent["multilogin_profile"] = merged
            else:
                api_agent["multilogin_profile"] = profile
        else:
            api_agent["multilogin_profile"] = copy.deepcopy(DEFAULT_MULTILOGIN_PROFILE)

        # Handle custom_start_urls - if provided, set startup_behavior to custom
        custom_urls = agent.get("custom_start_urls")
        if custom_urls:
            api_agent["multilogin_profile"]["parameters"]["custom_start_urls"] = custom_urls
            api_agent["multilogin_profile"]["parameters"]["flags"]["startup_behavior"] = "custom"

        return api_agent

    def _convert_queue(
        self,
        queue: Dict[str, Any],
        defaults: Dict[str, Any]
    ) -> Dict[str, Any]:
        """Convert queue section to API format."""
        # Handle start_at - supports "now", relative offsets (+5m, +1h), or ISO 8601
        start_at = queue.get("start_at", queue.get("start"))
        if not start_at:
            start_at = "now"  # Default to now
        start_at = parse_relative_time(start_at)

        api_queue = {
            "name": queue.get("name", "Session"),
            "description": queue.get("description", "Generated session"),
            "start_at": start_at,
            "timezone": queue.get("timezone", defaults.get("timezone", "America/Chicago")),
            "timezone_utc_offset": queue.get(
                "timezone_utc_offset",
                defaults.get("timezone_utc_offset", "-06:00")
            ),
            "active": True,
        }

        # Convert jobs
        api_queue["jobs"] = [
            self._convert_job(job, defaults)
            for job in queue.get("jobs", [])
        ]

        return api_queue

    def _convert_job(
        self,
        job: Dict[str, Any],
        defaults: Dict[str, Any]
    ) -> Dict[str, Any]:
        """Convert job to API format."""
        api_job = {
            "name": job.get("name", "Job"),
            "type": job.get("type", "waitjob"),
            "description": job.get("description", "Generated job"),
            "active": True,
        }

        # Convert behaviors
        behaviors = job.get("behaviors", [])
        if isinstance(behaviors, dict):
            # Convert dict format to list
            api_job["behaviors"] = [
                {
                    "name": name,
                    "value": value,
                    "description": "",
                    "active": True,
                }
                for name, value in behaviors.items()
            ]
        else:
            # Already list format
            api_job["behaviors"] = [
                self._convert_behavior(b)
                for b in behaviors
            ]

        return api_job

    def _convert_behavior(self, behavior: Dict[str, Any]) -> Dict[str, Any]:
        """Convert behavior to API format."""
        return {
            "name": behavior.get("name", ""),
            "value": behavior.get("value"),
            "description": behavior.get("description", ""),
            "active": behavior.get("active", True),
        }

    def _deep_merge(
        self,
        base: Dict[str, Any],
        override: Dict[str, Any]
    ) -> None:
        """Deep merge override into base dict (in-place)."""
        for key, value in override.items():
            if key in base and isinstance(base[key], dict) and isinstance(value, dict):
                self._deep_merge(base[key], value)
            else:
                base[key] = value


def convert_yaml_to_json(yaml_content: str, pretty: bool = True) -> str:
    """
    Convenience function to convert YAML spec to JSON.

    Args:
        yaml_content: YAML string
        pretty: Whether to format with indentation

    Returns:
        JSON string
    """
    converter = SpecConverter()
    result = converter.convert_from_yaml(yaml_content)

    if result.errors:
        raise ValueError(f"Conversion errors: {result.errors}")

    return result.to_json(pretty=pretty)
