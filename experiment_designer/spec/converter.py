"""
Spec Converter - Convert parsed YAML to API-compatible JSON.

Produces JSON that matches the PrimeMover API upload format:
- ExperimentUploadRequest validation rules
- CrawlerDto structure
- Proper nesting of configuration, agent, proxy, queues, jobs, behaviors
"""

import copy
import json
from dataclasses import dataclass, field
from typing import Any

from .design_expander import DesignExpander
from .parser import ParsedSpec, SpecParser
from .time_utils import parse_relative_time

# The params the API contract defines explicit columns for; everything else in a
# spec's params block is passed through untouched (see _convert_configuration).
_STANDARD_PARAM_KEYS = frozenset(
    {"pi", "psi", "alpha", "tau", "kappa", "beta", "active", "search_terms", "media_outlet_urls"}
)


@dataclass
class ConversionResult:
    """Result of converting a spec to JSON."""

    json_data: list[dict[str, Any]]  # Array of crawler objects for API
    experiment_name: str
    experiment_description: str
    crawler_count: int
    total_jobs: int
    experiment_runner_user_id: int | None = None  # None = the API's default runner
    errors: list[str] = field(default_factory=list)
    warnings: list[str] = field(default_factory=list)

    def to_json(self, pretty: bool = True) -> str:
        """Convert to JSON string."""
        if pretty:
            return json.dumps(self.json_data, indent=2, ensure_ascii=False)
        return json.dumps(self.json_data, ensure_ascii=False)


