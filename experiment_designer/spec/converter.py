class SpecConverter:
    """
    Convert parsed YAML spec to API-compatible JSON.

    Example usage:
        parser = SpecParser()
        parsed = parser.parse(yaml_content)

        converter = SpecConverter()
        result = converter.convert(parsed)

        if result.errors:
            print("Errors:", result.errors)
        else:
            api_json = result.to_json()
    """

    def __init__(
        self, *, seed: int | None = None, resolve_times: bool = True, lax: bool = False
    ) -> None:
        self.errors: list[str] = []
        self.warnings: list[str] = []
        # An explicit seed wins over design.seed so a compile can pin every draw
        # from one number; None keeps today's behaviour (design.seed or unseeded).
        self.seed = seed
        # False leaves queue start strings as written ("+5m", "now", ISO) so the
        # lock compiler can express them as offsets from an anchor.
        self.resolve_times = resolve_times
        self.lax = lax
        self.drops = Drops(lax)
        # design.parameters names outside _STANDARD_PARAM_KEYS for the spec
        # being converted; set per convert() and read by _convert_configuration.
        self._sampled_substitution_params: frozenset[str] = frozenset()

    def _runner_user_id(self, experiment: dict[str, Any]) -> int | None:
        """experiment.runner_user_id, validated; None when absent."""
        value = experiment.get("runner_user_id")
        if value is None:
            return None
        if isinstance(value, bool) or not isinstance(value, int):
            self.errors.append(
                "experiment.runner_user_id must be an integer runner account id (1 = ex63, 3 = VM)"
            )
            return None
        return value

    def convert(self, parsed: ParsedSpec) -> ConversionResult:
        """
        Convert a parsed spec to API JSON format.

        Args:
            parsed: Parsed specification

        Returns:
            ConversionResult with JSON data
        """
        self.errors = list(parsed.errors)  # Copy any parsing errors
        self.warnings = list(parsed.warnings)
        self.drops = Drops(self.lax)
        runner_user_id = self._runner_user_id(parsed.experiment)

        if self.errors:
            return ConversionResult(
                json_data=[],
                experiment_name=parsed.experiment.get("name", ""),
                experiment_description=parsed.experiment.get("description", ""),
                crawler_count=0,
                total_jobs=0,
                experiment_runner_user_id=runner_user_id,
                errors=self.errors,
                warnings=self.warnings,
            )

        # Expand design if present
        # Extract seed from design for reproducibility
        design_seed = parsed.design.get("seed") if parsed.design else None
        self._sampled_substitution_params = self.sampled_substitution_params(parsed.design)
        effective_seed = self.seed if self.seed is not None else design_seed
        expander = DesignExpander(seed=effective_seed)
        all_crawlers = []

        for crawler_template in parsed.crawlers:
            # Check if this crawler uses the design
            if crawler_template.get("from_design") and parsed.design:
                expanded = expander.expand(parsed.design, crawler_template)
                all_crawlers.extend(expanded)
                self.errors.extend(expander.errors)
                self.warnings.extend(expander.warnings)
            else:
                all_crawlers.append(crawler_template)

        # Resolve data-pool references now that design expansion has fixed each
        # crawler's params (pi, kappa, alpha, ...) -- pool scoring expressions
        # read those from the crawler context.
        if parsed.pool_manager is not None:
            resolved_crawlers = []
            for crawler in all_crawlers:
                context = {
                    k: v
                    for k, v in crawler.get("configuration", {}).get("params", {}).items()
                    if not isinstance(v, (dict, list))
                }
                resolved_crawlers.append(
                    resolve_pool_references(crawler, parsed.pool_manager, context)
                )
            all_crawlers = resolved_crawlers
            self.errors.extend(parsed.pool_manager.errors)
            self.warnings.extend(parsed.pool_manager.warnings)
            parsed.pool_manager.errors = []
            parsed.pool_manager.warnings = []

        # Resolve per-bot template draws (deferred `%%pmspec-draw:...%%` tokens
        # from a `with: {from_pool: ..., field: ...}` value) now that each
        # crawler's identity (name, index) is fixed -- one seeded draw sequence
        # per crawler, without replacement within it. A token that fails to
        # resolve is left in place; `_scan_unresolved` below reports it as a
        # drop, so it can never reach a lock.
        self.errors.extend(resolve_draws(all_crawlers, parsed.pool_manager, effective_seed))

        # A crawler without its own proxy block inherits `defaults.proxy`. Copy it
        # onto the crawler *before* pool assignment, or a pooled default
        # (`defaults: {proxy: {from_pool: true, ...}}`) reaches _convert_proxy as
        # a raw dict with no hostname and every bot silently compiles to the
        # 127.0.0.1:8080 placeholder. Non-dict defaults ("none"/"auto") keep the
        # fallback in _convert_crawler.
        default_proxy = parsed.defaults.get("proxy")
        if isinstance(default_proxy, dict):
            all_crawlers = [
                {**c, "proxy": copy.deepcopy(default_proxy)} if c.get("proxy") is None else c
                for c in all_crawlers
            ]

        # Assign one pool row per `proxy: {from_pool: true}` crawler now that
        # design expansion and pool-reference resolution have fixed each
        # crawler's agent/location.
        self._assign_pool_proxies(all_crawlers, parsed.pool_manager)

        # Convert each crawler to API format
        api_crawlers = []
        total_jobs = 0

        for i, crawler in enumerate(all_crawlers):
            proxy = crawler.get("proxy")
            if isinstance(proxy, dict) and proxy.get("from_pool") is True:
                # Pool assignment refused this crawler (error already recorded);
                # converting the raw marker would yield the 127.0.0.1 placeholder.
                continue
            try:
                api_crawler = self._convert_crawler(crawler, parsed.defaults)
                api_crawlers.append(api_crawler)

                # Count jobs
                for queue in api_crawler.get("queues", []):
                    total_jobs += len(queue.get("jobs", []))

            except Exception as e:
                self.errors.append(f"Error converting crawler {i}: {e}")

        self._scan_unresolved(api_crawlers)

        self.drops.merge_into(self.errors, self.warnings)

        return ConversionResult(
            json_data=api_crawlers,
            experiment_name=parsed.experiment.get("name", ""),
            experiment_description=parsed.experiment.get("description", ""),
            crawler_count=len(api_crawlers),
            total_jobs=total_jobs,
            experiment_runner_user_id=runner_user_id,
            experiment_contact=parsed.experiment.get("contact"),
            errors=self.errors,
            warnings=self.warnings,
            dropped=self.drops.count,
        )

    def convert_from_yaml(self, yaml_content: str) -> ConversionResult:
        """
        Convenience method to parse and convert in one step.

        Args:
            yaml_content: YAML string

        Returns:
            ConversionResult with JSON data
        """
        parser = SpecParser()
        parsed = parser.parse(yaml_content)
        return self.convert(parsed)

    def _convert_crawler(self, crawler: dict[str, Any], defaults: dict[str, Any]) -> dict[str, Any]:
        """
        Convert a crawler to API format.

        Args:
            crawler: Parsed crawler definition
            defaults: Merged defaults

        Returns:
            API-compatible crawler dict
        """
        api_crawler = {
            "name": crawler.get("name", "Crawler"),
            "description": crawler.get("description", "Generated crawler"),
            "active": 1 if crawler.get("active", True) else 0,
            "testing": 1 if crawler.get("testing", False) else 0,
        }

        # Convert configuration
        api_crawler["configuration"] = self._convert_configuration(
            crawler.get("configuration", {}), defaults
        )

        # Convert proxy - use crawler proxy, or fall back to defaults.proxy
        proxy_config = crawler.get("proxy")
        if proxy_config is None:
            proxy_config = defaults.get("proxy", {})
        api_crawler["proxy"] = self._convert_proxy(proxy_config, defaults)

        # Convert agent
        api_crawler["agent"] = self._convert_agent(crawler.get("agent", {}), defaults)

        # Convert queues
        api_crawler["queues"] = [
            self._convert_queue(q, defaults) for q in crawler.get("queues", [])
        ]

        return api_crawler

    @staticmethod
    def sampled_substitution_params(design: dict[str, Any] | None) -> frozenset[str]:
        """`design.parameters` names that are not standard params.

        DesignExpander writes every sampled value into
        `configuration.params.<name>`; for these names that key is dead on
        arrival (the API keeps only the standard columns), so their only
        legitimate use is as a `{name}` substitution variable -- which the
        validator enforces (an unreferenced one is a drop) and which
        _convert_configuration relies on to strip them.
        """
        parameters = (design or {}).get("parameters")
        if not isinstance(parameters, dict):
            return frozenset()
        return frozenset(name for name in parameters if name not in _STANDARD_PARAM_KEYS)

    def _convert_configuration(
        self, config: dict[str, Any], defaults: dict[str, Any]
    ) -> dict[str, Any]:
        """Convert configuration section to API format."""
        api_config = {
            "name": config.get("name", "Configuration"),
            "description": config.get("description", "Generated configuration"),
            "active": 1,  # API expects integer for configuration.active
        }

        # Convert params. The standard keys are always emitted with defaults so the
        # API/runner/decision-function contract is satisfied. Any additional keys
        # are passed through rather than dropped, so a spec can carry experiment-
        # specific treatment config forward (the validator warns that the current
        # typed pipeline does not yet deliver such keys; the generic channel is the
        # flexible-treatment work). Standard keys win over passthrough.
        #
        # The one exception is a non-standard `design.parameters` name: the
        # expander put it here by default, but its value has already been
        # substituted wherever the spec referenced `{name}` (the validator
        # refuses a spec that references it nowhere), and the API would drop
        # the key anyway. Stripping it keeps the emitted params honest and
        # keeps the strict scan from seeing a "dropped" param that was in fact
        # consumed. Only those names are stripped; a hand-written extra key in
        # a crawler's own params block still passes through as before. The
        # strip is by name alone -- a hand-written params key that happens to
        # share a sampled parameter's name goes too -- and the validator, not
        # this method, is the gate that decides whether the spec is acceptable.
        params = config.get("params", {})
        extra = {
            k: v
            for k, v in params.items()
            if k not in _STANDARD_PARAM_KEYS and k not in self._sampled_substitution_params
        }
        api_config["params"] = {
            **extra,
            "pi": params.get("pi", 0),
            "psi": params.get("psi", 0),
            "alpha": params.get("alpha", 1),
            "tau": params.get("tau", 0),
            "kappa": params.get("kappa", 0),
            "beta": params.get("beta", 0),
            "active": True,
            "search_terms": params.get("search_terms", []),
            "media_outlet_urls": params.get("media_outlet_urls", []),
        }

        # Convert preferences
        prefs = config.get("preferences", [])
        api_config["preferences"] = self._ensure_preferences(prefs, defaults)

        return api_config

    def _ensure_preferences(
        self, prefs: list[dict[str, Any]], defaults: dict[str, Any]
    ) -> list[dict[str, Any]]:
        """Ensure required preferences are present."""
        api_prefs = []
        pref_names = set()

        # Add existing preferences
        for pref in prefs:
            api_pref = {
                "name": pref.get("name", ""),
                "description": pref.get("description", pref.get("name", "")),
                "value": self._format_pref_value(pref.get("value")),
                "active": pref.get("active", True),
            }
            api_prefs.append(api_pref)
            pref_names.add(pref.get("name"))

        # Add default preferences if not present
        default_prefs = [
            ("location", defaults.get("location", "US-IL-CHICAGO")),
            ("cookie_pref", '{"accept_all": true}'),
            ("usage_type", "only_search"),
        ]

        for name, value in default_prefs:
            if name not in pref_names:
                api_prefs.append(
                    {
                        "name": name,
                        "description": name,
                        "value": value,
                        "active": True,
                    }
                )

        return api_prefs

    def _format_pref_value(self, value: Any) -> str:
        """Format a preference value as string."""
        if isinstance(value, dict):
            return json.dumps(value)
        if isinstance(value, bool):
            return str(value).lower()
        return str(value) if value is not None else ""

    def _assign_pool_proxies(
        self, crawlers: list[dict[str, Any]], pool_manager: DataPoolManager | None
    ) -> None:
        """Give each `proxy: {from_pool: true}` crawler its own row of the named pool.

        One exit IP per bot is the study requirement (a shared IP is both a
        detection signal and a confound across arms), so rows are handed out
        without replacement, in pool order, to crawlers in spec order; running
        out is an error, not a shared proxy.
        """
        used: dict[str, set[int]] = {}
        # Pools already found to have no hostname/host column: reported once,
        # then every crawler drawing from them is skipped without repeating it.
        unusable: set[str] = set()
        for i, crawler in enumerate(crawlers):
            proxy = crawler.get("proxy")
            if not (isinstance(proxy, dict) and proxy.get("from_pool") is True):
                continue
            prefix = f"crawlers[{i}].proxy"
            pool_name = proxy.get("pool")
            field = proxy.get("match_field")
            if not pool_name or not field:
                self.errors.append(f"{prefix}: from_pool needs `pool:` and `match_field:`")
                continue
            rows = pool_manager.rows(str(pool_name)) if pool_manager else None
            if rows is None:
                self.errors.append(
                    f"{prefix}: unknown pool '{pool_name}' (define it under data_pools)"
                )
                continue
            pool_name = str(pool_name)
            # An empty hostname is the runner's "no proxy" signal, so a pool whose
            # rows have no hostname/host column at all (`ip`, say) would turn
            # every bot into a direct connection. Checked once per pool.
            if pool_name not in unusable and pool_name not in used:
                if not any(("hostname" in row or "host" in row) for row in rows):
                    columns = sorted({str(k) for row in rows for k in row})
                    self.errors.append(
                        f"{prefix}: pool '{pool_name}' has no hostname/host column, so its "
                        f"rows would compile to direct connections (columns: {columns}); "
                        "name the proxy host column `hostname`"
                    )
                    unusable.add(pool_name)
            if pool_name in unusable:
                continue
            location = (crawler.get("agent") or {}).get("location")
            if not location:
                self.errors.append(
                    f"{prefix}: from_pool matches on the agent's location, and "
                    f"crawlers[{i}].agent has none"
                )
                continue
            taken = used.setdefault(pool_name, set())
            candidates = [k for k, row in enumerate(rows) if str(row.get(field)) == str(location)]
            free = [k for k in candidates if k not in taken]
            if not candidates:
                self.errors.append(
                    f"{prefix}: pool '{pool_name}' has no row with {field} == {location!r}"
                )
                continue
            if not free:
                self.errors.append(
                    f"{prefix}: pool '{pool_name}' has {len(candidates)} row(s) for {field} == "
                    f"{location!r}, all already assigned; crawler '{crawler.get('name')}' gets none"
                )
                continue
            row = rows[free[0]]
            host = row.get("hostname") or row.get("host") or ""
            port = row.get("port")
            if not str(host).strip() or port in (None, "", 0):
                # The row itself is blank where it matters; refuse it rather than
                # hand this bot a direct connection. It stays assigned so the
                # next crawler does not inherit the same broken row.
                taken.add(free[0])
                self.errors.append(
                    f"{prefix}: pool '{pool_name}' row {free[0]} has no hostname/port "
                    f"(columns: {sorted(str(k) for k in row)})"
                )
                continue
            taken.add(free[0])
            crawler["proxy"] = {
                "name": f"{pool_name}:{host}:{row.get('port', '')}",
                "description": f"from pool {pool_name} for {location}",
                "hostname": host,
                "port": port,
                "username": row.get("username", ""),
                "password": row.get("password", ""),
                "type": row.get("type") or "http",
                "active": True,
            }

    def _convert_proxy(self, proxy: dict[str, Any], defaults: dict[str, Any]) -> dict[str, Any]:
        """Convert proxy section to API format."""
        # Handle 'none' - no proxy (empty hostname signals runner to skip proxy)
        if proxy == "none":
            return {
                "name": "No Proxy",
                "description": "Direct connection - no proxy",
                "hostname": "",
                "port": 0,
                "username": "",
                "password": "",
                "active": True,
                "type": "http",  # Must be valid type; empty hostname indicates no proxy
            }

        # Handle 'auto' or minimal proxy config
        if proxy == "auto" or not proxy:
            proxy = {}

        proxy_type = proxy.get("type", defaults.get("proxy_type", "http"))

        # Oxylabs is self-configuring: the runner supplies the endpoint and the
        # account from its own config (oxylabs.hostname/.port/.customer/.password),
        # so a spec needs only `type: oxylabs`. Geo-targeting comes from the agent's
        # location, not from here, so filling in a placeholder host or repeating the
        # account per crawler would only put credentials in git for no benefit.
        if proxy_type == "oxylabs":
            default_host, default_port = "", 0
        else:
            default_host, default_port = "127.0.0.1", 8080

        return {
            "name": proxy.get("name", "Proxy"),
            "description": proxy.get("description", "Generated proxy"),
            "hostname": proxy.get("hostname", proxy.get("host", default_host)),
            "port": int(proxy.get("port", default_port)),
            "username": proxy.get("username", ""),
            "password": proxy.get("password", ""),
            "active": True,
            "type": proxy_type,
        }

    def _convert_agent(self, agent: dict[str, Any], defaults: dict[str, Any]) -> dict[str, Any]:
        """Convert agent section to API format."""
        api_agent = {
            "name": agent.get("name", "Agent"),
            "description": agent.get("description", "Generated agent"),
            "identification": agent.get("identification", defaults.get("browser", "mlx")),
            "multilogin_id": agent.get("multilogin_id"),
            "location": agent.get("location", defaults.get("location", "US-IL-CHICAGO")),
            "active": 1,
        }

        # Handle multilogin_profile
        profile = agent.get("multilogin_profile")
        if profile:
            if isinstance(profile, dict):
                # Merge with defaults
                merged = copy.deepcopy(DEFAULT_MULTILOGIN_PROFILE)
                self._deep_merge(merged, profile)
                api_agent["multilogin_profile"] = merged
            else:
                api_agent["multilogin_profile"] = profile
        else:
            api_agent["multilogin_profile"] = copy.deepcopy(DEFAULT_MULTILOGIN_PROFILE)

        # Handle custom_start_urls - if provided, set startup_behavior to custom
        custom_urls = agent.get("custom_start_urls")
        if custom_urls:
            api_agent["multilogin_profile"]["parameters"]["custom_start_urls"] = custom_urls
            api_agent["multilogin_profile"]["parameters"]["flags"]["startup_behavior"] = "custom"

        return api_agent

    def _convert_queue(self, queue: dict[str, Any], defaults: dict[str, Any]) -> dict[str, Any]:
        """Convert queue section to API format."""
        # Handle start_at - supports "now", relative offsets (+5m, +1h), or ISO 8601
        start_at = queue.get("start_at", queue.get("start"))
        if not start_at:
            start_at = "now"
        if self.resolve_times:
            start_at = parse_relative_time(start_at)

        api_queue = {
            "name": queue.get("name", "Session"),
            "description": queue.get("description", "Generated session"),
            "start_at": start_at,
            "timezone": queue.get("timezone", defaults.get("timezone", "America/Chicago")),
            "timezone_utc_offset": queue.get(
                "timezone_utc_offset", defaults.get("timezone_utc_offset", "-06:00")
            ),
            "active": True,
        }

        # Convert jobs
        api_queue["jobs"] = [self._convert_job(job, defaults) for job in queue.get("jobs", [])]

        return api_queue

    def _convert_job(self, job: dict[str, Any], defaults: dict[str, Any]) -> dict[str, Any]:
        """Convert job to API format."""
        api_job = {
            "name": job.get("name", "Job"),
            "type": job.get("type", "waitjob"),
            "description": job.get("description", "Generated job"),
            "active": True,
        }

        # Convert behaviors
        behaviors = job.get("behaviors", [])
        if isinstance(behaviors, dict):
            # Convert dict format to list
            api_job["behaviors"] = [
                {
                    "name": name,
                    "value": value,
                    "description": "",
                    "active": True,
                }
                for name, value in behaviors.items()
            ]
        else:
            # Already list format
            api_job["behaviors"] = [self._convert_behavior(b) for b in behaviors]

        return api_job

    def _convert_behavior(self, behavior: dict[str, Any]) -> dict[str, Any]:
        """Convert behavior to API format."""
        return {
            "name": behavior.get("name", ""),
            "value": behavior.get("value"),
            "description": behavior.get("description", ""),
            "active": behavior.get("active", True),
        }

    def _scan_unresolved(self, api_crawlers: list[dict[str, Any]]) -> None:
        """Report every DSL variable that survived expansion.

        `${var}` is a template variable nobody supplied via `with:`; `{var}` is a
        design variable no factor or parameter defines. Either reaches the runner
        (and the decision function) as a literal string, which is the silent
        failure the strict contract exists to end. The Multilogin profile is
        skipped: it is a JSON document with its own %%TOKEN%% placeholders.
        """

        # One `${query}` in a template used by 300 bots x 4 jobs is one mistake,
        # not 1200: group by (token, path with every index replaced by [*]) and
        # report each group once, with the count and the first concrete path.
        groups: dict[tuple[str, str], list[str]] = {}
        # A surviving `%%pmspec-draw:...%%` token: `resolve_draws` failed on it
        # (unknown pool, missing field, exhaustion -- already in self.errors)
        # and left it in place rather than guess. Reported separately so the
        # message names it as a draw, not a plain unresolved variable. Matched
        # loosely (ANY_DRAW_TOKEN_RE) on purpose: a token DRAW_TOKEN_RE cannot
        # parse is *more* certain to reach the bot as a literal, not less.
        draw_groups: dict[tuple[str, str], list[str]] = {}

        def walk(node: Any, path: str) -> None:
            if isinstance(node, str):
                for m in _UNRESOLVED_RE.finditer(node):
                    generic = _INDEX_RE.sub("[*]", path)
                    groups.setdefault((m.group(0), generic), []).append(path)
                for m in ANY_DRAW_TOKEN_RE.finditer(node):
                    generic = _INDEX_RE.sub("[*]", path)
                    draw_groups.setdefault((m.group(0), generic), []).append(path)
            elif isinstance(node, dict):
                for k, v in node.items():
                    if k == "multilogin_profile":
                        continue
                    walk(v, f"{path}.{k}")
            elif isinstance(node, list):
                for i, v in enumerate(node):
                    if isinstance(v, dict) and "name" in v and "value" in v:
                        walk(v["value"], f"{path}.{v['name']}")
                    else:
                        walk(v, f"{path}[{i}]")

        for i, crawler in enumerate(api_crawlers):
            walk(crawler, f"crawlers[{i}]")

        fix = "supply it with `with:` on the template call, or define it as a factor/parameter"
        for (token, generic), places in groups.items():
            if len(places) == 1:
                self.drops.report(
                    places[0],
                    f"unresolved variable {token!r} would reach the bot as a literal",
                    fix,
                )
            else:
                self.drops.report(
                    generic,
                    f"unresolved variable {token!r} would reach the bot as a literal in "
                    f"{len(places)} place(s) (first: {places[0]})",
                    fix,
                )

        draw_fix = "see the unknown-pool/missing-field/exhaustion error reported above"
        for (token, generic), places in draw_groups.items():
            if len(places) == 1:
                self.drops.report(
                    places[0],
                    f"unresolved pool draw {token!r} would reach the bot as a literal",
                    draw_fix,
                )
            else:
                self.drops.report(
                    generic,
                    f"unresolved pool draw {token!r} would reach the bot as a literal in "
                    f"{len(places)} place(s) (first: {places[0]})",
                    draw_fix,
                )

    def _deep_merge(self, base: dict[str, Any], override: dict[str, Any]) -> None:
        """Deep merge override into base dict (in-place)."""
        for key, value in override.items():
            if key in base and isinstance(base[key], dict) and isinstance(value, dict):
                self._deep_merge(base[key], value)
            else:
                base[key] = value


def convert_yaml_to_json(yaml_content: str, pretty: bool = True) -> str:
    """
    Convenience function to convert YAML spec to JSON.

    Args:
        yaml_content: YAML string
        pretty: Whether to format with indentation

    Returns:
        JSON string
    """
    converter = SpecConverter()
    result = converter.convert_from_yaml(yaml_content)

    if result.errors:
        raise ValueError(f"Conversion errors: {result.errors}")

    return result.to_json(pretty=pretty)
